client.on('messageCreate', async message=>{
  if (message.author.bot||!message.content.startsWith('!')||!message.guild) return;
  const args=message.content.slice(1).trim().split(/ +/);
  const cmd=args.shift().toLowerCase();
  const queue=getQueue(message.guild.id);

  try {
    if (cmd==='play'||cmd==='p') {
      const query=cleanQuery(args.join(' '));
      if (!query) return message.reply('❌ Kasih nama lagu atau link!');
      const vc=message.member?.voice?.channel;
      if (!vc) return message.reply('❌ Join voice channel dulu!');
      const loading=await message.reply(`🔍 Mencari **${query}**...`);
      queue.textChannel=message.channel;
      return handlePlay(loading, query, message.guild.id, vc, message.channel, message.author.username);
    }
    if (cmd==='search'||cmd==='sc') {
      const query=cleanQuery(args.join(' '));
      if (!query) return message.reply('❌ Kasih nama lagu yang mau dicari!');
      const loading=await message.reply(`🔍 Mencari **${query}**...`);
      let results;
      try { results=await searchMultiple(query, message.author.username); }
      catch(err){ return safeEdit(loading, `❌ ${err.message}`); }

      const desc=results.map((t,i)=>`\`${i+1}.\` [${t.title}](${t.url}) \`${t.duration}\``).join('\n');
      const embed=new EmbedBuilder()
        .setColor(0x5865f2)
        .setTitle(`🔍 Hasil pencarian: "${query}"`)
        .setDescription(desc)
        .setFooter({text:'Klik tombol untuk memutar lagu'});
      const row=new ActionRowBuilder().addComponents(
        results.map((t,i)=>
          new ButtonBuilder()
            .setCustomId(`search_pick_${t.url}`)
            .setLabel(`${i+1}. ${t.title.slice(0,40)}`)
            .setStyle(ButtonStyle.Secondary)
        )
      );
      return safeEdit(loading,'',{embeds:[embed], components:[row]});
    }
    if (cmd==='skip'||cmd==='s'){
      if (!queue.player||!queue.currentTrack) return message.reply('❌ Tidak ada yang diputar.');
      queue.loop=false;
      if (queue.ytdlpProc) { try{queue.ytdlpProc.kill('SIGKILL');}catch(_){} queue.ytdlpProc=null; }
      playNext(message.guild.id);
      return message.reply('⏭️ Di-skip!');
    }
    if (cmd==='stop') return cmdStopMsg(message,queue);
    if (cmd==='pause'){
      if (!queue.player) return message.reply('❌ Tidak ada yang diputar.');
      queue.player.pause();
      if (queue.playerMsg&&queue.currentTrack) safeEdit(queue.playerMsg,'',buildPausedEmbed(queue.currentTrack,queue));
      return message.reply('⏸️ Di-pause.');
    }
    if (cmd==='resume'||cmd==='r'){
      if (!queue.player) return message.reply('❌ Tidak ada yang diputar.');
      queue.player.unpause();
      if (queue.playerMsg&&queue.currentTrack) safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,0));
      return message.reply('▶️ Dilanjutkan.');
    }
    if (cmd==='loop'||cmd==='l'){
      queue.loop=!queue.loop;
      return message.reply(`🔁 Loop **${queue.loop?'ON':'OFF'}**.`);
    }
    if (cmd==='autoplay'||cmd==='ap'){
      queue.autoplay=!queue.autoplay;
      return message.reply(`🔀 Autoplay **${queue.autoplay?'ON':'OFF'}**.`);
    }
    if (cmd==='queue'||cmd==='q') return cmdQueueMsg(message,queue);
    if (cmd==='clear'){ queue.tracks=[]; return message.reply('🗑️ Antrian dikosongkan!'); }
    if (cmd==='np'||cmd==='nowplaying'){
      if (!queue.currentTrack) return message.reply('❌ Tidak ada yang diputar.');
      const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
      return message.reply(buildPlayerEmbed(queue.currentTrack,queue,el));
    }
    if (cmd==='help'||cmd==='h') return message.reply({embeds:[buildHelpEmbed()]});
    if (cmd==='aliases') return message.reply({embeds:[buildAliasEmbed()]});
  } catch(err){
    console.error('cmd error:',err);
    message.reply(`❌ Error: ${err.message}`).catch(()=>{});
  }
});

