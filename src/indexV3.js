// ─── Helpers ──────────────────────────────────────────────────────────────────
function formatDuration(sec) {
  sec = Math.floor(sec||0);
  const h=Math.floor(sec/3600), m=Math.floor((sec%3600)/60), s=sec%60;
  if (h>0) return `${h}:${String(m).padStart(2,'0')}:${String(s).padStart(2,'0')}`;
  return `${m}:${String(s).padStart(2,'0')}`;
}
function parseDuration(str) {
  if (!str||str==='N/A') return 0;
  const p=str.split(':').map(Number);
  if (p.length===3) return p[0]*3600+p[1]*60+p[2];
  if (p.length===2) return p[0]*60+p[1];
  return 0;
}
function buildProgressBar(elapsed, total, width=18) {
  if (!total) return '▬'.repeat(width);
  const pos=Math.min(Math.floor((elapsed/total)*width), width-1);
  return '▬'.repeat(pos)+'🔘'+'▬'.repeat(width-pos);
}
function cleanQuery(q) {
  q=q.replace(/<(https?:\/\/[^>]+)>/g,'$1');
  q=q.replace(/\[.*?\]\((https?:\/\/[^)]+)\)/g,'$1');
  return q.trim();
}
async function safeEdit(msg, content, opts={}) {
  try {
    if (!msg?.editable) return;
    if (content?.length>2000) content=content.slice(0,1997)+'...';
    await msg.edit({ content, ...opts });
  } catch(err){ if(err.code!==10008) console.error('safeEdit:',err.message); }
}

