// ─── Stream ───────────────────────────────────────────────────────────────────
function createYtdlpStream(url) {
  const args=[
    url,'-o','-',
    '-f','bestaudio[ext=webm]/bestaudio/best',
    '--no-playlist','--quiet','--no-warnings',
    // Spoof sebagai iOS — bypass bot detection YouTube
    '--extractor-args','youtube:player_client=ios',
    ...(hasCookies?['--cookies',cookiePath]:[]),
  ];
  const proc=spawn(ytdlpBin, args, {stdio:['ignore','pipe','pipe']});
  proc.stderr.on('data', d=>{
    const m=d.toString().trim();
    if(m && !m.includes('Broken pipe') && !m.includes('unable to write data')) console.warn('[yt-dlp]',m);
  });
  proc.on('error', err=>console.error('[yt-dlp spawn]',err.message));
  proc.stdout.on('error', ()=>{}); // suppress EPIPE / premature close saat skip
  return { stream: proc.stdout, proc };
}

