// ─── Search ───────────────────────────────────────────────────────────────────
async function searchTrack(query, requester) {
  const isUrl=/^https?:\/\//i.test(query);
  const searchQuery=isUrl?query:`ytsearch1:${query}`;
  const args={
    dumpSingleJson:true, noCheckCertificates:true,
    noWarnings:true, preferFreeFormats:true,
    skipDownload:true,
    // Spoof sebagai iOS app — lebih susah dideteksi YouTube dibanding bot
    extractorArgs:'youtube:player_client=ios',
    ...(isUrl?{flatPlaylist:true}:{}),
    ...(hasCookies?{cookies:cookiePath}:{}),
  };
  const info=await ytdlp(searchQuery,args).catch(err=>{
    console.error('yt-dlp error:',err.message);
    throw new Error('Gagal mengambil info lagu');
  });
  const v=info.entries?info.entries[0]:info;
  // webpage_url ada kalau full fetch; url ada kalau flat-playlist / search result
  const videoUrl=v?.webpage_url||v?.url||(v?.id?`https://www.youtube.com/watch?v=${v.id}`:null);
  if (!videoUrl) throw new Error('Lagu tidak ditemukan.');
  return {
    title:    v.title||'Unknown',
    url:      videoUrl,
    duration: v.duration?formatDuration(v.duration):'N/A',
    thumbnail:v.thumbnail||null,
    videoId:  v.id||null,
    requester,
  };
}

