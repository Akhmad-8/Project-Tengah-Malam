// ─── playNext ─────────────────────────────────────────────────────────────────
async function playNext(guildId) {
  const queue=getQueue(guildId);
  const textChannel=queue.textChannel;

  // Nonaktifkan tombol di player lama tanpa menghapus pesan
  if (queue.playerMsg) {
    try {
      await queue.playerMsg.edit({
        embeds: queue.playerMsg.embeds,
        components:[]
      });
    } catch(_){}
    queue.playerMsg=null;
  }

  // Autoplay kalau antrian kosong
  if (!queue.tracks.length && queue.autoplay && queue.currentTrack?.videoId) {
    const related=await getRelatedTrack(queue.currentTrack.videoId, queue.currentTrack.title, 'Autoplay');
    if (related) {
      queue.tracks.push(related);
      if (textChannel) textChannel.send({
        embeds:[new EmbedBuilder().setColor(0x43b581)
          .setDescription(`🔀 **Autoplay:** [${related.title}](${related.url})`)]
      }).catch(()=>{});
    }
  }

  if (!queue.tracks.length) {
    queue.currentTrack=null;
    if (textChannel) textChannel.send('✅ Antrian habis!').catch(()=>{});
    return;
  }

  const track=queue.tracks.shift();
  // Simpan ke history sebelum ganti currentTrack (max 20 lagu)
  if (queue.currentTrack) {
    queue.history.push({...queue.currentTrack});
    if (queue.history.length > 20) queue.history.shift();
  }
  queue.currentTrack=track;
  queue.startTime=Date.now();

  // Kill proses yt-dlp sebelumnya kalau masih jalan
  if (queue.ytdlpProc) {
    try { queue.ytdlpProc.kill('SIGKILL'); } catch(_){}
    queue.ytdlpProc=null;
  }

  try {
    const {stream, proc}=createYtdlpStream(track.url);
    queue.ytdlpProc=proc; // simpan referensi untuk di-kill saat skip
    const resource=createAudioResource(stream,{inputType:StreamType.Arbitrary});
    queue.player.play(resource);
    if (textChannel) {
      queue.playerMsg=await textChannel.send(buildPlayerEmbed(track,queue,0)).catch(()=>null);
    }
  } catch(err){
    console.error('playNext error:',err.message);
    if (textChannel) textChannel.send(`❌ Gagal memutar **${track.title}**: ${err.message}`).catch(()=>{});
    setTimeout(()=>playNext(guildId), 1000);
  }
}

// ─── Setup player untuk guild ─────────────────────────────────────────────────
function setupPlayer(guildId) {
  const queue=getQueue(guildId);
  if (queue.player) return; // sudah ada

  queue.player=createAudioPlayer();
  queue.connection.subscribe(queue.player);

  queue.player.on(AudioPlayerStatus.Idle, ()=>{
    if (queue.isTransitioning) return; // sudah ada yang handle
    queue.isTransitioning=true;
    if (queue.loop && queue.currentTrack) {
      queue.tracks.unshift({...queue.currentTrack});
    }
    setTimeout(()=>{ queue.isTransitioning=false; playNext(guildId); }, 500);
  });

  queue.player.on('error', err=>{
    console.error('Player error:',err.message);
    if (queue.isTransitioning) return; // Idle sudah handle, abaikan error dari stream kill
    queue.isTransitioning=true;
    if (queue.textChannel) queue.textChannel.send(`❌ Error: ${err.message}`).catch(()=>{});
    setTimeout(()=>{ queue.isTransitioning=false; playNext(guildId); }, 1000);
  });
}

// ─── handlePlay ───────────────────────────────────────────────────────────────
async function handlePlay(ctx, query, guildId, voiceChannel, textChannel, username) {
  const queue=getQueue(guildId);
  queue.textChannel=textChannel;

  const replyFn=async(content,opts={})=>{
    try {
      if (ctx.isChatInputCommand?.()) {
        if (ctx.deferred||ctx.replied) return ctx.editReply({content,...opts});
        return ctx.reply({content,...opts});
      }
      return safeEdit(ctx, content, opts);
    } catch(_){}
  };

  let trackInfo;
  try { trackInfo=await searchTrack(query, username); }
  catch(err){
    console.error('searchTrack:',err.message);
    return replyFn('❌ Gagal cari lagu. Coba link YouTube langsung.');
  }

  queue.tracks.push(trackInfo);

  if (!queue.connection) {
    try {
      queue.connection=joinVoiceChannel({
        channelId:voiceChannel.id,
        guildId,
        adapterCreator:voiceChannel.guild.voiceAdapterCreator,
        selfDeaf:true,
      });
      await entersState(queue.connection, VoiceConnectionStatus.Ready, 15_000);
    } catch(err){
      if (queue.connection){queue.connection.destroy();queue.connection=null;}
      queue.tracks.pop();
      return replyFn(`❌ Gagal join VC: ${err.message}`);
    }

    setupPlayer(guildId);

    if (ctx.isChatInputCommand?.()) await replyFn(`✅ Memutar **${trackInfo.title}**`);
    else { try{await ctx.delete();}catch(_){} }

    playNext(guildId);

  } else {
    setupPlayer(guildId); // pastikan player ada
    const embed=new EmbedBuilder().setColor(0x1db954).setTitle('➕ Ditambahkan ke Antrian')
      .setDescription(`**[${trackInfo.title}](${trackInfo.url})**`)
      .addFields(
        {name:'⏱ Durasi',  value:trackInfo.duration,           inline:true},
        {name:'👤 Request', value:trackInfo.requester,           inline:true},
        {name:'📋 Posisi',  value:`#${queue.tracks.length}`,    inline:true}
      ).setThumbnail(trackInfo.thumbnail);
    await replyFn('',{embeds:[embed]});

    // Kalau tidak ada yang diputar (antrian habis sebelumnya), langsung putar
    if (!queue.currentTrack) playNext(guildId);
  }
}

// ─── Button handler ───────────────────────────────────────────────────────────
client.on('interactionCreate', async interaction=>{
  if (interaction.isButton()) {
    const queue=getQueue(interaction.guildId);
    await interaction.deferUpdate().catch(()=>{});

    switch(interaction.customId){
      case 'btn_pause':
        if (queue.player?.state.status===AudioPlayerStatus.Playing){
          queue.player.pause();
          if (queue.playerMsg&&queue.currentTrack)
            await safeEdit(queue.playerMsg,'',buildPausedEmbed(queue.currentTrack,queue));
        }
        break;
      case 'btn_resume':
        if (queue.player?.state.status===AudioPlayerStatus.Paused){
          queue.player.unpause();
          if (queue.playerMsg&&queue.currentTrack)
            await safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,0));
        }
        break;
      case 'btn_skip':
        if (!queue.player || !queue.currentTrack) break;
        queue.loop=false;
        // Kill yt-dlp lama, langsung play berikutnya — tidak pakai stop() biar tidak ada double Idle event
        if (queue.ytdlpProc) { try{queue.ytdlpProc.kill('SIGKILL');}catch(_){} queue.ytdlpProc=null; }
        playNext(interaction.guildId);
        break;
      case 'btn_stop':
        queue.tracks=[];queue.currentTrack=null;queue.loop=false;
        if (queue.player){queue.player.removeAllListeners();queue.player.stop(true);}
        queue.connection?.destroy();
        if (queue.playerMsg) await safeEdit(queue.playerMsg,'⏹️ Musik dihentikan.',{embeds:[],components:[]});
        queue.playerMsg=null;queue.connection=null;queue.player=null;
        queues.delete(interaction.guildId);
        break;
      case 'btn_loop':
        queue.loop=!queue.loop;
        if (queue.playerMsg&&queue.currentTrack){
          const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
          await safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,el));
        }
        break;
      case 'btn_prev':
        if (!queue.player) break;
        queue.loop=false;
        if (queue.history && queue.history.length > 0) {
          const prevTrack=queue.history.pop();
          if (queue.currentTrack) queue.tracks.unshift({...queue.currentTrack});
          queue.tracks.unshift(prevTrack);
        } else if (queue.currentTrack) {
          queue.tracks.unshift({...queue.currentTrack});
        } else { break; }
        if (queue.ytdlpProc) { try{queue.ytdlpProc.kill('SIGKILL');}catch(_){} queue.ytdlpProc=null; }
        queue.currentTrack=null;
        playNext(interaction.guildId);
        break;
      default:
        // Handler tombol hasil search: format customId = "search_pick_{index}_{url}"
        if (interaction.customId.startsWith('search_pick_')) {
          const url=interaction.customId.split('search_pick_')[1];
          const vc=interaction.member?.voice?.channel;
          if (!vc) {
            await interaction.update({content:'❌ Join voice channel dulu!', embeds:[], components:[]});
            return;
          }
          await interaction.update({content:`🔍 Memuat...`, embeds:[], components:[]});
          await handlePlay(interaction, url, interaction.guildId, vc, interaction.channel, interaction.user.username);
        }
        break;
    }
    return;
  }

  // ─── Slash commands ──────────────────────────────────────────────────────
  if (!interaction.isChatInputCommand()) return;
  const {commandName, guildId}=interaction;
  if (!guildId) return interaction.reply({content:'❌ Hanya bisa di server.',ephemeral:true});

  const queue=getQueue(guildId);

  // Play aliases
  if (commandName==='play'||commandName==='p') {
    const query=cleanQuery(interaction.options.getString('lagu'));
    await interaction.deferReply();
    const vc=interaction.member?.voice?.channel;
    if (!vc) return interaction.editReply('❌ Join voice channel dulu!');
    return handlePlay(interaction, query, guildId, vc, interaction.channel, interaction.user.username);
  }

  // Search aliases
  if (commandName==='search'||commandName==='sc') {
    const query=cleanQuery(interaction.options.getString('query'));
    await interaction.deferReply();
    let results;
    try { results=await searchMultiple(query, interaction.user.username); }
    catch(err){ return interaction.editReply(`❌ ${err.message}`); }

    // Buat embed daftar hasil
    const desc=results.map((t,i)=>`\`${i+1}.\` [${t.title}](${t.url}) \`${t.duration}\``).join('\n');
    const embed=new EmbedBuilder()
      .setColor(0x5865f2)
      .setTitle(`🔍 Hasil pencarian: "${query}"`)
      .setDescription(desc)
      .setFooter({text:'Klik tombol untuk memutar lagu'});

    // Buat tombol 1-5 per hasil
    const row=new ActionRowBuilder().addComponents(
      results.map((t,i)=>
        new ButtonBuilder()
          .setCustomId(`search_pick_${t.url}`)
          .setLabel(`${i+1}. ${t.title.slice(0,40)}`)
          .setStyle(ButtonStyle.Secondary)
      )
    );

    return interaction.editReply({embeds:[embed], components:[row]});
  }

  // Skip aliases
  if (commandName==='skip'||commandName==='s') {
    if (!queue.player||!queue.currentTrack) return interaction.reply({content:'❌ Tidak ada yang diputar.',ephemeral:true});
    await interaction.reply({content:'⏭️ Di-skip!',ephemeral:true});
    queue.loop=false;
    if (queue.ytdlpProc) { try{queue.ytdlpProc.kill('SIGKILL');}catch(_){} queue.ytdlpProc=null; }
    playNext(guildId);
    return;
  }

  // Controls aliases
  if (['controls','control','c','ct'].includes(commandName)) {
    if (!queue.currentTrack) return interaction.reply({content:'❌ Tidak ada yang diputar.',ephemeral:true});
    const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
    return interaction.reply(buildPlayerEmbed(queue.currentTrack,queue,el));
  }

  switch(commandName){
    case 'stop':
      if (!queue.connection) return interaction.reply({content:'❌ Bot tidak di VC.',ephemeral:true});
      queue.tracks=[];queue.currentTrack=null;queue.loop=false;
      if (queue.player){queue.player.removeAllListeners();queue.player.stop(true);}
      queue.connection?.destroy();
      if (queue.playerMsg) await safeEdit(queue.playerMsg,'⏹️ Musik dihentikan.',{embeds:[],components:[]});
      queue.playerMsg=null;queue.connection=null;queue.player=null;
      queues.delete(guildId);
      return interaction.reply({content:'⏹️ Bot keluar VC.',ephemeral:true});

    case 'pause':
      if (!queue.player) return interaction.reply({content:'❌ Tidak ada yang diputar.',ephemeral:true});
      queue.player.pause();
      if (queue.playerMsg&&queue.currentTrack) await safeEdit(queue.playerMsg,'',buildPausedEmbed(queue.currentTrack,queue));
      return interaction.reply({content:'⏸️ Di-pause.',ephemeral:true});

    case 'resume': case 'r':
      if (!queue.player) return interaction.reply({content:'❌ Tidak ada yang diputar.',ephemeral:true});
      queue.player.unpause();
      if (queue.playerMsg&&queue.currentTrack) await safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,0));
      return interaction.reply({content:'▶️ Dilanjutkan.',ephemeral:true});

    case 'loop': case 'l':
      queue.loop=!queue.loop;
      if (queue.playerMsg&&queue.currentTrack){
        const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
        await safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,el));
      }
      return interaction.reply({content:`🔁 Loop **${queue.loop?'ON':'OFF'}**.`,ephemeral:true});

    case 'autoplay': case 'ap':
      queue.autoplay=!queue.autoplay;
      if (queue.playerMsg&&queue.currentTrack){
        const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
        await safeEdit(queue.playerMsg,'',buildPlayerEmbed(queue.currentTrack,queue,el));
      }
      return interaction.reply({content:`🔀 Autoplay **${queue.autoplay?'ON':'OFF'}**.`,ephemeral:true});

    case 'queue': case 'q': {
      if (!queue.currentTrack&&!queue.tracks.length)
        return interaction.reply({content:'📋 Antrian kosong!',ephemeral:true});
      let desc=queue.currentTrack?`▶️ **Sekarang:** [${queue.currentTrack.title}](${queue.currentTrack.url})\n\n`:'';
      if (queue.tracks.length){
        desc+=queue.tracks.slice(0,10).map((t,i)=>`\`${i+1}.\` [${t.title}](${t.url}) — ${t.duration}`).join('\n');
        if (queue.tracks.length>10) desc+=`\n...dan ${queue.tracks.length-10} lagu lainnya.`;
      }
      return interaction.reply({embeds:[new EmbedBuilder().setColor(0x1db954)
        .setTitle(`📋 Antrian — ${queue.tracks.length} lagu`).setDescription(desc||'Kosong')]});
    }

    case 'clear':
      queue.tracks=[];
      return interaction.reply({content:'🗑️ Antrian dikosongkan!',ephemeral:true});

    case 'nowplaying': case 'np': {
      if (!queue.currentTrack) return interaction.reply({content:'❌ Tidak ada yang diputar.',ephemeral:true});
      const el=queue.startTime?(Date.now()-queue.startTime)/1000:0;
      return interaction.reply(buildPlayerEmbed(queue.currentTrack,queue,el));
    }

    case 'help': case 'h':
      return interaction.reply({embeds:[buildHelpEmbed()],ephemeral:false});

    case 'aliases':
      return interaction.reply({embeds:[buildAliasEmbed()],ephemeral:true});

    case 'changelog':
      return interaction.reply({embeds:[new EmbedBuilder().setColor(0x5865f2)
        .setTitle('📋 Changelog')
        .setDescription('**v2.0.0** — Slash commands + Autoplay + Player embed dengan tombol\n**v1.0.0** — Rilis awal dengan prefix commands')
      ],ephemeral:true});
  }
});

