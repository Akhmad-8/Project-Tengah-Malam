function prepareNetscapeCookies() {
  try {
    if (!fs.existsSync(rawCookiePath)) return false;
    const raw = fs.readFileSync(rawCookiePath, 'utf-8').trim();
    if (raw.includes('# Netscape HTTP Cookie File')) {
      fs.copyFileSync(rawCookiePath, netscapeCookiePath); return true;
    }
    const lines = ['# Netscape HTTP Cookie File','# Generated by bot',''];
    raw.split(';').forEach(pair => {
      const [name,...rest] = pair.trim().split('=');
      if (!name||!rest.length) return;
      lines.push(`.youtube.com\tTRUE\t/\tTRUE\t1999999999\t${name.trim()}\t${rest.join('=').trim()}`);
    });
    fs.writeFileSync(netscapeCookiePath, lines.join('\n'));
    console.log('✅ Cookie dikonversi ke format Netscape');
    return true;
  } catch (err) { console.warn('⚠️ Cookie prep gagal:', err.message); return false; }
}
const hasCookies = prepareNetscapeCookies();
const cookiePath = hasCookies ? netscapeCookiePath : null;

